# Plays the whole experience and measures the loudness (RMS) of every sound event through an analyser on the master bus.
import asyncio, json
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox","--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader","--autoplay-policy=no-user-gesture-required"])
        pg = await b.new_page(viewport={"width":1280,"height":760}); errs=[]
        pg.on("pageerror", lambda e: errs.append(str(e)))
        await pg.add_init_script("""window.__peak={}; window.__meter=(name,ms)=>new Promise(r=>{let m=0;const t0=performance.now();const f=()=>{m=Math.max(m,__tlf.audio.level());if(performance.now()-t0<ms)setTimeout(f,15);else{__peak[name]=+m.toFixed(4);r(m)}};f()});""")
        await pg.goto("http://localhost:8777/index.html?dtmax=0.25")
        await pg.wait_for_function("window.__tlf && window.__tlf.ready", timeout=180000)
        await pg.click("#start")
        await pg.evaluate("__meter('signal_static', 1200)")
        await pg.evaluate("__meter('beacon_beeps', 2500)")
        await pg.wait_for_function("__tlf.S.stage==='home'", timeout=180000, polling=50)
        await pg.wait_for_timeout(3000)
        await pg.evaluate("__meter('space_ambient', 1500)")
        await pg.click("#go-warp")
        await pg.wait_for_function("document.querySelector('#guide-text').textContent.length > 3", timeout=60000, polling=30)
        await pg.evaluate("__meter('guide_voice', 2000)")
        await pg.click("#guide-chips button[data-site='spirit']")
        await pg.evaluate("__meter('pick_ping', 600)")
        await pg.wait_for_function("window.__tlf.surfaceReady", timeout=180000)
        await pg.click("#guide-land")
        await pg.evaluate("__meter('warp_whoosh', 2500)")
        await pg.wait_for_function("__tlf.S.mode==='hall'", timeout=180000, polling=50)
        await pg.evaluate("__meter('mars_wind', 1500)")
        await pg.keyboard.down("Space")
        await pg.evaluate("__meter('charge_hum', 800)")
        await pg.wait_for_function("__tlf.S.mode==='firing'", timeout=60000, polling=20)
        await pg.keyboard.up("Space")
        await pg.evaluate("__meter('zap_and_chime', 1500)")
        await pg.wait_for_function("document.querySelector('#bubble').classList.contains('show')", timeout=120000, polling=50)
        await pg.evaluate("__meter('rover_voice', 2000)")
        await pg.click("#mute")
        await pg.evaluate("__meter('muted', 800)")
        print(json.dumps(await pg.evaluate("__peak"), indent=1)); print("errors", errs[:5])
        await b.close()
asyncio.run(main())
